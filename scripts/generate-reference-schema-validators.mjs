import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaFiles = [
  "nodekit.reference-loop-observation.v1.schema.json",
  "nodekit.reference-loop-design-rule.v1.schema.json",
  "nodekit.reference-score-receipt.v1.schema.json",
  "nodekit.external-reference-run.v1.schema.json",
  "nodekit.reference-profile-manifest.v1.schema.json",
  "nodekit.reference-chain-edge.v1.schema.json",
];
const schemas = await Promise.all(schemaFiles.map(async (name) =>
  JSON.parse(await readFile(path.join(repoRoot, "schemas", name), "utf8"))));
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  schemas,
  code: { source: true },
});
addFormats(ajv);

const code = standaloneCode(ajv, {
  validateReferenceObservation: "nodekit.reference-loop-observation/v1",
  validateDesignRule: "nodekit.reference-loop-design-rule/v1",
  validateReferenceScoreReceipt: "nodekit.reference-score-receipt/v1",
  validateExternalReferenceRun: "nodekit.external-reference-run/v1",
  validateReferenceProfileManifest: "nodekit.reference-profile-manifest/v1",
  validateReferenceChainEdge: "nodekit.reference-chain-edge/v1",
});
const banner = "// Generated by scripts/generate-reference-schema-validators.mjs. Do not edit by hand.\n";
const output = `${banner}${code}\n`;
const target = path.join(repoRoot, "src", "lib", "reference-schema-validators.cjs");
if (process.argv.includes("--check")) {
  const existing = await readFile(target, "utf8");
  if (existing !== output) {
    throw new Error("reference schema validators are stale; run npm run reference:schemas");
  }
} else {
  await writeFile(target, output, "utf8");
}
