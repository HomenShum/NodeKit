// EXPLAIN-stage producer for the mew migration. Mechanical where it can be, refusing where it
// cannot:
//   - inputs[] digests are recomputed from the artifacts actually read, never copied from a note.
//   - buildBinding evidenceRefs are resolved from the BuildEvidencePack by artifact PATH; a path
//     that resolves to no evidence entry refuses the whole pack.
//   - every statement is phrase-scanned against the committed lexicon (claim-lexicon.json) at its
//     recorded digest; the scan record is generated by this run, not asserted by an author.
//   - the pack validates against nodekit.story-pack.v1.schema.json before it is written.
//
// Content honesty: no data exists anywhere in this journey (zero notes, zero cases — the wave-0
// receipts). So content.sources is EMPTY, every rendered claim has rendersData:false, and every
// claim the story wanted to make about the owner's data lives in withheldClaims with a reason.
//
//   node scripts/produce-story-pack.mjs [--chain-dir ../../proof/mew-migration/chain] [--out <path>]

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
function opt(name, fallback) {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
}
const chainDir = path.resolve(opt("--chain-dir", path.join(here, "..", "..", "..", "proof", "mew-migration", "chain")));
const outPath = path.resolve(opt("--out", path.join(chainDir, "mew-migration.story-pack.json")));
