const lexiconRaw = await readFile(path.join(here, "claim-lexicon.json"), "utf8");
const lexicon = JSON.parse(lexiconRaw);
const lexiconDigest = canonicalSha256(lexicon);
const producedAt = new Date().toISOString().replace(/\.\d+Z$/, (m) => `.${m.slice(1, 4)}Z`);

function evidenceIdByPath(suffix) {
  const entry = bep.content.evidence.find((e) => e.artifact.path.endsWith(suffix));
  if (!entry) throw new Error(`REFUSED: no BuildEvidencePack evidence entry has a path ending "${suffix}"; a story claim may not cite evidence that is not in the pack`);
  return entry.evidenceId;
}

function scan(statement) {
  const lower = statement.toLowerCase();
  const matches = [];
  for (const { phrase, implies } of lexicon.phrases) {
    const offset = lower.indexOf(phrase.toLowerCase());
    if (offset >= 0) matches.push({ phrase: statement.slice(offset, offset + phrase.length), implies, offset });
  }
  return {
    scanner: "apps/mew-migration/scripts/produce-story-pack.mjs#scan",
    scannerVersion: "1.0.0",
    lexiconDigest,
    scannedAt: producedAt,
    matches,
  };
}

function boundClaim({ claimId, statement, surfaceRefs, evidencePaths, boundary }) {
  const claim = {
    claimId,
    statement,
    surfaceRefs,
    consequential: true,
    rendersData: false,
    dataImplications: [],
    phraseScan: scan(statement),
    status: "bound",
    buildBinding: {
      bepClaimIds: [],
      evidenceRefs: [...new Set(evidencePaths.map(evidenceIdByPath))],
      restatement: "simplified",
      strengthDelta: "equal",
    },
    boundary,
  };
  if (claim.phraseScan.matches.length > 0) {
    throw new Error(`REFUSED: claim ${claimId} matched regulated phrases [${claim.phraseScan.matches.map((m) => m.phrase).join(", ")}] but was authored as a software-only claim; reword it or bind it as data`);
  }
  return claim;
}

